// Devuelve el archivo (no la URL) de una foto: "img (1).png".
// El index.html de R2 sirve el objeto con su Content-Disposition original, así que
// al abrirlo en una pestaña el móvil guarda un nombre que no es el de la foto o
// directamente lo muestra en vez de descargarlo. Con `download` sí se respeta.
function nombreArchivo(src) {
    try {
        return decodeURIComponent(src.split("/").pop()) || "foto-monocromatics.jpg";
    } catch (err) {
        return "foto-monocromatics.jpg";
    }
}

// ¿La URL sirve para descargar por fetch (blob)? Solo si es del mismo origen que
// R2_PUBLIC_URL. Así este archivo se puede reutilizar con otras rutas sin intentar
// descargar como blob una imagen local (donde `download` ya funciona igual).
function esUrlDescargable(src) {
    try {
        return new URL(src, window.location.href).origin === new URL(R2_PUBLIC_URL, window.location.href).origin;
    } catch (err) {
        return false;
    }
}

// Aviso visible cuando el data-carpeta del apartado apunta a una fiesta que ya
// no existe en galeria.js (por ejemplo, si se renombro la carpeta o se borro la
// fiesta). Antes esto solo dejaba un console.warn y el visitante veia una pagina
// en blanco sin saber por que. Ahora se pinta un mensaje con un enlace de vuelta.
function mostrarFiestaNoDisponible() {
    const aviso = document.createElement("section");
    aviso.className = "galeria-vacia";

    const titulo = document.createElement("h2");
    titulo.textContent = "Esta fiesta ya no está disponible";

    const texto = document.createElement("p");
    texto.textContent = "Es posible que se haya renombrado o que sus fotos ya no estén publicadas. Puedes ver el resto de la galería aquí.";

    const enlace = document.createElement("a");
    enlace.className = "button";
    enlace.href = "galeria.html";
    enlace.textContent = "VER TODA LA GALERÍA";

    aviso.appendChild(titulo);
    aviso.appendChild(texto);
    aviso.appendChild(enlace);
    contenedor.appendChild(aviso);
}

// Guard: este script también puede cargarse en páginas sin la galería.
// Sin el contenedor no hay nada que pintar, así que salimos sin romper
// el resto de scripts (proxima_fiesta.js, artistas.js, etc.).
if (!contenedor) {
    console.warn("galeria.js: no existe #fiestas-galeria en esta página; no se pinta la galería.");
} else {
    // Si el contenedor tiene data-carpeta, solo mostramos esa fiesta.
    // Si no lo tiene, mostramos todas.
    //
    // El valor es SIEMPRE la CARPETA de la fiesta (`DOPPLER_dsm_14_05_26`), que es
    // el identificador estable. Se sigue aceptando tambien el NOMBRE visible por
    // las paginas antiguas que aun no se hayan regenerado, pero ya no deberia
    // hacer falta: esa ambiguedad (comparar nombre y carpeta) fue la que provoco
    // el bug de "una tarjeta abre las fotos de otra fiesta".
    const carpetaSolicitada = (contenedor.dataset.carpeta || "").trim().toLowerCase();

    const fiestasAMostrar = carpetaSolicitada
        ? fiestas.filter(f =>
            f.carpeta.trim().toLowerCase() === carpetaSolicitada ||
            f.nombre.trim().toLowerCase() === carpetaSolicitada
        )
        : fiestas;

    if (carpetaSolicitada && fiestasAMostrar.length === 0) {
        console.warn(`No se encontró ninguna fiesta con carpeta ni nombre "${carpetaSolicitada}" en galeria.js`);
        mostrarFiestaNoDisponible();
    }

    // Lista plana de todas las fotos visibles en esta página, en el mismo orden
    // en que se pintan. Es lo que usa el visor para ir a la anterior/siguiente,
    // incluso saltando de una fiesta a la siguiente.
    fotosVisibles = fiestasAMostrar.flatMap(fiesta =>
        fiesta.fotos.map(foto => `${R2_PUBLIC_URL}/imagenes/fiestas/${fiesta.carpeta}/${foto}`)
    );

    let indiceRelativo = 0;

    fiestasAMostrar.forEach(fiesta => {
        const seccion = document.createElement("section");
        seccion.className = "galeria-fiesta";

        const titulo = document.createElement("h2");
        titulo.textContent = fiesta.nombre;

        const lugar = document.createElement("p");
        lugar.textContent = fiesta.lugar;

        const grid = document.createElement("div");
        grid.className = "gallery-grid";

        // Copia del valor actual: el clic se ejecuta mucho después, cuando
        // indiceRelativo ya ha seguido sumando. Sin esto el índice se sale de rango.
        const base = indiceRelativo;

        fiesta.fotos.forEach((foto, indice) => {
            const img = document.createElement("img");

            img.src = `${R2_PUBLIC_URL}/imagenes/fiestas/${fiesta.carpeta}/${foto}`;
            img.alt = `Monocromatics ${fiesta.nombre}`;
            img.loading = "lazy";
            img.decoding = "async";

            // Si una foto se borro de R2 alguna vez, deja de existir para siempre
            // en esa ruta. Sin esto quedaba un hueco con el icono de imagen rota.
            img.addEventListener("error", () => {
                img.remove();
            });

            img.addEventListener("click", () => abrirFoto(base + indice));

            grid.appendChild(img);
        });

        indiceRelativo += fiesta.fotos.length;

        seccion.appendChild(titulo);
        seccion.appendChild(lugar);
        seccion.appendChild(grid);
        contenedor.appendChild(seccion);
    });
}

/* ==========================================================
   VISOR DE FOTO
   Permite ir a la foto anterior/siguiente con las flechas de la
   pantalla o del teclado (← →), y bloquea el scroll del fondo
   mientras está abierto.
========================================================== */

let visorAbierto = null;

function abrirFoto(indice) {
    if (indice < 0 || indice >= fotosVisibles.length) {
        return;
    }

    // Si ya hay un visor abierto, lo cerramos para no apilar capas.
    if (visorAbierto) {
        visorAbierto.cerrar();
    }

    let indiceActual = indice;

    const visor = document.createElement("div");
    visor.className = "visor-foto";
    visor.setAttribute("role", "dialog");
    visor.setAttribute("aria-modal", "true");
    visor.setAttribute("aria-label", "Visor de fotos");

    const botonCerrar = document.createElement("button");
    botonCerrar.type = "button";
    botonCerrar.className = "cerrar-visor";
    botonCerrar.textContent = "×";
    botonCerrar.setAttribute("aria-label", "Cerrar visor");

    const botonAnterior = document.createElement("button");
    botonAnterior.type = "button";
    botonAnterior.className = "visor-nav visor-prev";
    botonAnterior.textContent = "←";
    botonAnterior.setAttribute("aria-label", "Foto anterior");

    const botonSiguiente = document.createElement("button");
    botonSiguiente.type = "button";
    botonSiguiente.className = "visor-nav visor-next";
    botonSiguiente.textContent = "→";
    botonSiguiente.setAttribute("aria-label", "Foto siguiente");

    const imagen = document.createElement("img");
    imagen.alt = "Foto Monocromatics";

    const descargar = document.createElement("a");
    descargar.className = "descargar-foto";
    descargar.textContent = "DESCARGAR";
    descargar.rel = "noopener";

    // En R2 el enlace directo NO sirve: el atributo `download` se ignora entre
    // dominios distintos, así que el móvil abría la foto en una pestaña en vez de
    // bajarla. Y si el navegador no la sabe mostrar (algún .HEIC/.avif recién
    // subido), la pestaña quedaba en blanco.
    //
    // Ahora la descarga se hace SIEMPRE con un blob: se baja la foto a memoria y
    // se entrega con su nombre de archivo real (`download` sí se respeta en un
    // blob del mismo origen). Solo si el fetch falla (sin red o R2 sin CORS) se
    // vuelve al enlace directo de antes, así que nunca queda peor que antes.
    //
    // El "descargando…" no es cosmético: en móvil, con fotos de varios MB, entre
    // el toque y el aviso del sistema pasaban segundos sin ninguna señal y parecía
    // que el botón no funcionaba; se volvía a pulsar y se lanzaban descargas dobles.
    descargar.addEventListener("click", async e => {
        e.preventDefault();
        e.stopPropagation();

        if (descargar.dataset.ocupado === "1") return;

        const src = fotosVisibles[indiceActual];

        // Fuera de R2 (rutas locales) el enlace directo con `download` ya es correcto.
        if (!esUrlDescargable(src)) {
            const a = document.createElement("a");
            a.href = src;
            a.download = nombreArchivo(src);
            document.body.appendChild(a);
            a.click();
            a.remove();
            return;
        }

        const textoBoton = descargar.textContent;
        descargar.dataset.ocupado = "1";
        descargar.textContent = "DESCARGANDO…";

        try {
            const resp = await fetch(src, { mode: "cors" });
            if (!resp.ok) throw new Error(resp.status);

            const url = URL.createObjectURL(await resp.blob());
            const a = document.createElement("a");
            a.href = url;
            a.download = nombreArchivo(src);
            document.body.appendChild(a);
            a.click();
            a.remove();

            // 60s y no 1s: en móvil el navegador puede tardar en volcar el blob al
            // disco y revocarlo antes de tiempo cancela la descarga a medias.
            setTimeout(() => URL.revokeObjectURL(url), 60000);
        } catch (err) {
            console.warn("Descarga por blob no disponible, se abre la foto:", err);

            // Sin `target` apuntamos a la misma pestaña: `window.open` con
            // target="_blank" se considera pop-up y los móviles lo bloquean.
            const a = document.createElement("a");
            a.href = src;
            a.download = nombreArchivo(src);
            a.target = "_blank";
            a.rel = "noopener";
            document.body.appendChild(a);
            a.click();
            a.remove();
        } finally {
            descargar.dataset.ocupado = "0";
            descargar.textContent = textoBoton;
        }
    });

    const contador = document.createElement("p");
    contador.className = "visor-contador";

    function pintarFoto() {
        const src = fotosVisibles[indiceActual];

        imagen.src = src;

        // href/download solo se usan si el navegador ignora el preventDefault del
        // clic (p. ej. con el botón central del ratón). La descarga real la hace el
        // listener de arriba.
        descargar.href = src;
        descargar.download = nombreArchivo(src);

        contador.textContent = `${indiceActual + 1} / ${fotosVisibles.length}`;
    }

    function irA(delta) {
        // Navegación circular: de la última vuelve a la primera.
        indiceActual = (indiceActual + delta + fotosVisibles.length) % fotosVisibles.length;
        pintarFoto();
    }

    // Precarga discreta de las vecinas para que el cambio sea instantáneo.
    function precargarVecinas() {
        [-1, 1].forEach(delta => {
            const vecino = fotosVisibles[(indiceActual + delta + fotosVisibles.length) % fotosVisibles.length];
            if (vecino && vecino !== imagen.src) {
                new Image().src = vecino;
            }
        });
    }

    function cerrarVisor() {
        visor.remove();
        document.removeEventListener("keydown", alPulsarTecla);

        // Devolvemos el scroll al body tal y como estaba antes de abrir.
        document.body.classList.remove("visor-abierto");

        visorAbierto = null;
    }

    function alPulsarTecla(e) {
        if (e.key === "Escape") {
            cerrarVisor();
        } else if (e.key === "ArrowLeft") {
            irA(-1);
            precargarVecinas();
        } else if (e.key === "ArrowRight") {
            irA(1);
            precargarVecinas();
        }
    }

    botonAnterior.addEventListener("click", e => {
        e.stopPropagation();
        irA(-1);
        precargarVecinas();
    });

    botonSiguiente.addEventListener("click", e => {
        e.stopPropagation();
        irA(1);
        precargarVecinas();
    });

    botonCerrar.addEventListener("click", cerrarVisor);

    // Clic en el fondo (fuera de la imagen y de los botones) cierra el visor.
    visor.addEventListener("click", e => {
        if (e.target === visor) {
            cerrarVisor();
        }
    });

    visor.appendChild(botonCerrar);
    visor.appendChild(botonAnterior);
    visor.appendChild(imagen);
    visor.appendChild(botonSiguiente);
    visor.appendChild(contador);
    visor.appendChild(descargar);

    document.body.appendChild(visor);
    document.body.classList.add("visor-abierto");
    document.addEventListener("keydown", alPulsarTecla);

    pintarFoto();
    precargarVecinas();

    // Solo se muestran las flechas si hay más de una foto.
    const hayVarias = fotosVisibles.length > 1;
    botonAnterior.hidden = !hayVarias;
    botonSiguiente.hidden = !hayVarias;
    contador.hidden = !hayVarias;

    botonCerrar.focus();

    visorAbierto = { cerrar: cerrarVisor };
}